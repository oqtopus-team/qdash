"""Keep the Python client's generated models in step with the OpenAPI document."""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts/generate_python_client_models.py"
MODELS = ROOT / "clients/python/src/qdash/client/services/models.py"


def run_check(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(  # noqa: S603
        [sys.executable, str(SCRIPT), "--check", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def test_committed_models_match_the_openapi_document() -> None:
    result = run_check()

    assert result.returncode == 0, result.stdout + result.stderr


def test_check_reports_models_that_drifted_from_the_openapi_document(tmp_path: Path) -> None:
    drifted = tmp_path / "models.py"
    drifted.write_text(MODELS.read_text(encoding="utf-8") + "\n\nclass HandWritten: ...\n")

    result = run_check("--output", str(drifted))

    assert result.returncode != 0
    assert "is stale; run: task generate-python-schema" in result.stderr


def test_models_module_is_only_generated_code() -> None:
    text = MODELS.read_text(encoding="utf-8")

    assert text.startswith("# generated by datamodel-codegen:")
    # Handwritten client models live in client_models.py, outside the generated file.
    assert "Client representation of" not in text
