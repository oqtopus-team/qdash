class TestConfigurationDrivesTheResponse:
    def test_sdk_validates_the_configuration_offline(self) -> None:
        manager = QMFakeQuantumMachinesManager(_settings())
        config = _config()
        config["waveforms"]["x180_wf"] = {"type": "bogus", "sample": 0.2}

