class TestProgramDrivesTheResponse:
    """The device reads amplitudes, shots, elements and streams from the program itself."""

    def test_amplitudes_come_from_the_program(self) -> None:
        _, machine = _machine(noise_per_shot=0.0)
        shots = 4000
        low = np.linspace(0.0, 0.3, 4)
        high = np.linspace(0.6, 1.2, 4)

        for amplitudes in (low, high):
            job = machine.execute(rabi_like_program(amplitudes, shots))
            iq = _volts(job, "I") + 1j * _volts(job, "Q")
            # Projection noise of the averaged population is at most 0.5 / sqrt(shots).
            tolerance = 5 * 0.5 / math.sqrt(shots) * abs(EXCITED - GROUND)
            np.testing.assert_allclose(iq, _expected_iq(amplitudes), atol=tolerance)

    def test_extremes_are_exact_without_noise(self) -> None:
        _, machine = _machine(noise_per_shot=0.0)

        job = machine.execute(rabi_like_program(np.array([0.0, 0.6, 1.2]), 5))
        iq = _volts(job, "I") + 1j * _volts(job, "Q")

        np.testing.assert_allclose(iq, [GROUND, EXCITED, GROUND], atol=1e-7)

    def test_shot_count_comes_from_the_program(self) -> None:
        _, machine = _machine(noise_per_shot=0.02)
        # Steps of 2**-20 are exact in QUA fixed, so every shot plays all 400 points.
        amplitudes = np.arange(400) * 2.0**-20

        spreads = {}
        for shots in (4, 400):
            job = machine.execute(rabi_like_program(amplitudes, shots))
            assert _fetch(job, "iteration") == shots - 1
            assert job.fake_report["measurements"] == shots * amplitudes.size
            spreads[shots] = float(np.std(_volts(job, "I")))

        assert spreads[4] == pytest.approx(0.02 / 2, rel=0.15)
        assert spreads[400] == pytest.approx(0.02 / 20, rel=0.15)

    def test_loop_runs_in_qua_fixed_point_arithmetic(self) -> None:
        _, machine = _machine()
        # A 2.5e-9 step is below the 2**-28 resolution of QUA fixed: the program's own
        # loop condition, evaluated in fixed point, ends after fewer points than requested.
        amplitudes = np.linspace(0.0, 1e-6, 400)

        job = machine.execute(rabi_like_program(amplitudes, 4))

        played = job.fake_report["plays"]["qubit.x180"]
        assert played["count"] == job.fake_report["measurements"] < 4 * 400
        assert played["max_amplitude"] < 1e-6
        # Only complete buffers of 400 are averaged, as the stream processing says.
        assert _fetch(job, "I").shape == (400,)

    def test_stream_names_and_shapes_follow_the_stream_processing(self) -> None:
        _, machine = _machine()

        job = machine.execute(rabi_like_program(np.linspace(0, 1, 7), 3, names=("I_avg", "Q")))

        assert sorted(job.result_handles.keys()) == ["I_avg", "Q", "iteration"]
        assert job.result_handles.get("I") is None
        assert "I" not in job.result_handles
        assert _fetch(job, "I_avg").shape == (7,)

