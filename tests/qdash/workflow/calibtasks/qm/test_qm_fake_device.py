    def test_drive_amplitude_in_the_configuration_moves_the_pi_rotation(self) -> None:
        config = _config()
        config["waveforms"]["x180_wf"]["sample"] = 0.1
        backend = QMFakeBackend({"qm_fake_settings": _settings(qua_config=config)})
        task = QMAmplitudeRabi(
            {"run": {"amplitude_scale_range": {"value": (0.0, 1.9, 39)}, "shots": {"value": 1000}}}
        )

        fit = task.run(backend, "0").raw_result["fit"]

        # 0.1 V for 40 ns is 4 V*ns; pi_pulse_area 4.8 V*ns needs an amplitude scale of 1.2.
        assert fit.pi_amplitude_scale == pytest.approx(1.2, rel=0.02)

    def test_arbitrary_drive_waveform_uses_its_area(self) -> None:
        config = _config()
        samples = list(0.4 * np.sin(np.linspace(0, np.pi, 40)))
        config["waveforms"]["x180_wf"] = {"type": "arbitrary", "samples": samples}
        _, machine = _machine(qua_config=config, noise_per_shot=0.0)
        pi_scale = 4.8 / abs(sum(samples))

        job = machine.execute(rabi_like_program(np.array([0.0, pi_scale]), 3))
        iq = _volts(job, "I") + 1j * _volts(job, "Q")

        np.testing.assert_allclose(iq, [GROUND, EXCITED], atol=1e-6)

    def test_integration_weights_scale_the_demodulated_values(self) -> None:
        config = _config()
        for name in ("cosine_weights", "sine_weights", "minus_sine_weights"):
            weights = config["integration_weights"][name]
            weights["cosine"] = [[2 * value, length] for value, length in weights["cosine"]]
            weights["sine"] = [[2 * value, length] for value, length in weights["sine"]]
        _, machine = _machine(qua_config=config, noise_per_shot=0.0)

        job = machine.execute(rabi_like_program(np.array([0.0, 0.0001]), 2))

        # The tolerance is the QUA fixed resolution converted to volts.
        assert _volts(job, "I")[0] == pytest.approx(2 * GROUND.real, abs=1e-6)
        assert _volts(job, "Q")[0] == pytest.approx(2 * GROUND.imag, abs=1e-6)

    def test_weights_shorter_than_the_readout_are_unsupported(self) -> None:
        config = _config()
        config["integration_weights"]["cosine_weights"]["cosine"] = [[1.0, 100]]
        config["integration_weights"]["cosine_weights"]["sine"] = [[0.0, 100]]
        _, machine = _machine(qua_config=config)

        with pytest.raises(QMFakeUnsupportedError, match="covers 100 ns of a 200 ns"):
            machine.execute(rabi_like_program(np.linspace(0, 1, 3), 1))

    def test_single_output_demodulation_halves_the_signal(self) -> None:
        settings = _settings(noise_per_shot=0.0)
        settings = QMFakeSettings.model_validate(
            {
                **settings.model_dump(),
                "qubits": {
                    "0": {
                        **settings.qubits["0"].model_dump(),
                        "outputs": ["out1"],
                        "integration_weights": ["cos", "sin"],
                    }
                },
            }
        )
        manager = QMFakeQuantumMachinesManager(settings)
        session = QMFakeSession(manager=manager, settings=settings)

        result = run_rabi(session, "0", RabiSweep.create([0.0, 1e-4, 2e-4], 2, 16))

        # demod.full of one output gives half the amplitude; the library converts it
        # with demod2volts and no single_demod factor, as qualang-tools does.
        np.testing.assert_allclose(result.iq, 0.5 * (GROUND.real - 1j * GROUND.imag), rtol=1e-5)


