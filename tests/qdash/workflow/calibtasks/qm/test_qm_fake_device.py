def rabi_like_program(
    amplitudes: np.ndarray,
    shots: int,
    *,
    drive: tuple[str, str] = ("x180", "qubit"),
    readout: tuple[str, str] = ("readout", "resonator"),
    names: tuple[str, str] = ("I", "Q"),
    body: Callable[[Any], None] | None = None,
) -> Any:
    """A hand-written program with the structure of the qualang-tools 1D amplitude Rabi."""
    with qua.program() as prog:
        n = qua.declare(int)
        a = qua.declare(qua.fixed)
        i_var = qua.declare(qua.fixed)
        q_var = qua.declare(qua.fixed)
        i_st = qua.declare_output_stream()
        q_st = qua.declare_output_stream()
        n_st = qua.declare_output_stream()
        with qua.for_(n, 0, n < shots, n + 1):
            with qua.for_(*from_array(a, amplitudes)):
                if body is not None:
                    body(a)
                else:
                    qua.play(drive[0] * qua.amp(a), drive[1])
                qua.align("qubit", "resonator")
                qua.measure(
                    readout[0],
                    readout[1],
                    qua.dual_demod.full("cos", "out1", "sin", "out2", i_var),
                    qua.dual_demod.full("minus_sin", "out1", "cos", "out2", q_var),
                )
                qua.wait(250, "resonator")
                qua.save(i_var, i_st)
                qua.save(q_var, q_st)
            qua.save(n, n_st)
        with qua.stream_processing():
            i_st.buffer(len(amplitudes)).average().save(names[0])
            q_st.buffer(len(amplitudes)).average().save(names[1])
            n_st.save("iteration")
    return prog


def _fetch(job: Any, name: str) -> Any:
    handle = job.result_handles.get(name)
    assert handle is not None, f"no result named {name}"
    return handle.fetch_all()


def _volts(job: Any, name: str) -> np.ndarray:
    return np.asarray(unit().demod2volts(_fetch(job, name), READOUT_NS))


def _expected_iq(amplitudes: np.ndarray, pi_scale: float = 0.6) -> np.ndarray:
    population = np.sin(np.pi * np.asarray(amplitudes) / pi_scale / 2) ** 2
    return GROUND + (EXCITED - GROUND) * population


class RecordingManager:
    """Wraps the fake manager to record what crosses the device boundary."""

    def __init__(self, manager: QMFakeQuantumMachinesManager) -> None:
        self._manager = manager
        self.configs: list[dict[str, Any]] = []
        self.machines: list[QMFakeQuantumMachine] = []
        self.programs: list[Any] = []
        self.jobs: list[Any] = []

    def open_qm(self, config: dict[str, Any]) -> Any:
        self.configs.append(config)
        machine = self._manager.open_qm(config)
        self.machines.append(machine)
        recorder = self

        class Machine:
            def execute(self, program: Any) -> Any:
                recorder.programs.append(program)
                job = machine.execute(program)
                recorder.jobs.append(job)
                return job

            def close(self) -> bool:
                return machine.close()

        return Machine()


def _recording_session(**kwargs: Any) -> tuple[QMFakeSession, RecordingManager]:
    session = _backend(**kwargs).get_instance()
    recorder = RecordingManager(session.manager)
    return QMFakeSession(manager=cast("Any", recorder), settings=session.settings), recorder


