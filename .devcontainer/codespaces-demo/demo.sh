#!/usr/bin/env bash
# Start the QDash Demo (sample data): the Fake backend Compose stack behind
# Caddy on QDASH_DEMO_PORT (default 5714), seeded with a virtual chip and one
# run.
#
# Usage: demo.sh pull|start|stop|status|credentials|build-local
#
# pull and start use the prebuilt qdash-demo-* images that images.sh names for
# this commit; neither builds an image. When an image cannot be pulled, they
# stop with the reason. build-local builds the same images in this codespace
# instead, and runs only when asked for.
#
# The first run writes .env from .env.example with a random administrator
# password. Later runs reuse that .env and the database volumes, so start and
# restart are idempotent. An .env this script did not write is never changed.
# compose.yaml in this directory keeps MongoDB and PostgreSQL data in named
# volumes; stop keeps them, and deleting the codespace removes them.
#
# start waits up to QDASH_DEMO_READY_TIMEOUT seconds (default 600) for the
# services the seed needs, and stops early when one fails for good: a setup job
# exits with an error or a service keeps restarting.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$repo_root"

demo_dir=".devcontainer/codespaces-demo"
# shellcheck source-path=SCRIPTDIR source=images.sh
source "${demo_dir}/images.sh"
marker="# Generated by ${demo_dir}/demo.sh"
port="${QDASH_DEMO_PORT:-5714}"
# Only the services the demo needs: no AI runtime, mongo-express or tunnel.
services=(caddy user-flow-worker)
# Compose files of the demo, also written to .env as COMPOSE_FILE so plain
# `docker compose` commands in the codespace use the same volumes.
compose_files="compose.yaml:${demo_dir}/compose.yaml"
# What each service must reach before seeding: healthy (has a healthcheck),
# running, or completed (a one-shot setup job that exited 0).
ready_targets=(
  mongo:healthy
  postgres:healthy
  calibration-migration:completed
  agent-runtime-auth:completed
  prefect-server:healthy
  deployment-service:healthy
  api:running
  user-flow-worker:running
  ui:running
  caddy:running
)
ready_timeout="${QDASH_DEMO_READY_TIMEOUT:-600}"
ready_interval="${QDASH_DEMO_READY_INTERVAL:-5}"
# A service restarted this often is failing on every start.
max_restarts="${QDASH_DEMO_MAX_RESTARTS:-3}"

log() { printf '[qdash-demo] %s\n' "$*"; }

wait_for_docker() {
  for _ in $(seq 1 60); do
    docker info >/dev/null 2>&1 && return 0
    sleep 2
  done
  log "Docker is not available"
  exit 1
}

# Replace KEY=... in .env, or append it when the example has no such line.
set_env() {
  local key="$1" value="$2" tmp
  tmp="$(mktemp)"
  awk -v key="$key" -v value="$value" '
    index($0, key "=") == 1 { print key "=\"" value "\""; done = 1; next }
    { print }
    END { if (!done) print key "=\"" value "\"" }
  ' .env >"$tmp"
  mv "$tmp" .env
}

client_url() {
  if [ -n "${CODESPACE_NAME:-}" ] && [ -n "${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-}" ]; then
    echo "https://${CODESPACE_NAME}-${port}.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN}"
  else
    echo "http://localhost:${port}"
  fi
}

prepare_env() {
  if [ -f .env ]; then
    if ! grep -qxF "$marker" .env; then
      log ".env exists and was not written by this script; remove it or use the Setup guide"
      exit 1
    fi
  else
    log "Writing .env for the QDash Demo (sample data)"
    { echo "$marker"; cat .env.example; } >.env
    set_env ENV "$demo_env"
    set_env DEFAULT_BACKEND fake
    set_env UI_PORT "$port"
    set_env QDASH_ADMIN_USERNAME admin
    set_env QDASH_ADMIN_PASSWORD "$(head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)"
    # No QuEL hardware: keep the worker's credential mount inside the checkout.
    set_env QUELWARE_CLIENT_PATH ./.tmp/quelware-client
  fi
  # The forwarded URL follows the codespace name; keep it current.
  set_env CLIENT_URL "$(client_url)"
  # Also updates an .env written before the demo override existed.
  set_env COMPOSE_FILE "$compose_files"
  # The images of this commit; a pulled commit with new build inputs gets new tags.
  local images line
  images="$(images_main env)"
  for line in $images; do
    line="${line//\"/}"
    set_env "${line%%=*}" "${line#*=}"
  done
  mkdir -p config/qubex-config calib_data .tmp/quelware-client
}

compose() {
  local args=() file
  local IFS=:
  for file in $compose_files; do args+=(-f "$file"); done
  docker compose "${args[@]}" "$@"
}

# Print "service status health exit-code restart-count" for each container.
container_states() {
  local ids
  ids="$(compose ps -aq)"
  [ -n "$ids" ] || return 0
  # shellcheck disable=SC2086 # one argument per container ID
  docker inspect --format \
    '{{index .Config.Labels "com.docker.compose.service"}} {{.State.Status}} {{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}} {{.State.ExitCode}} {{.RestartCount}}' \
    $ids
}

# Show where startup stopped, then exit.
fail_startup() {
  local reason="$1"
  shift
  log "$reason"
  compose ps -a || true
  local service
  for service in "$@"; do
    log "Last log lines of ${service}:"
    compose logs --no-color --tail 40 "$service" || true
  done
  log "Fix the cause, then run: bash ${demo_dir}/demo.sh start"
  exit 1
}

# Wait until every ready_targets entry holds, or fail on a permanent error or
# after ready_timeout seconds.
wait_ready() {
  local deadline="$1" states target service want line
  local status health code restarts before pending baseline
  log "Waiting for the services (up to ${ready_timeout}s)"
  # Restart counts survive codespace restarts; count only new restarts.
  baseline="$(container_states)"
  while :; do
    states="$(container_states)"
    pending=()
    for target in "${ready_targets[@]}"; do
      service="${target%%:*}"
      want="${target#*:}"
      line="$(awk -v s="$service" '$1 == s { print; exit }' <<<"$states")"
      if [ -z "$line" ]; then
        pending+=("$service")
        continue
      fi
      read -r _ status health code restarts <<<"$line"
      if [ "$want" = completed ]; then
        if [ "$status" = exited ] && [ "$code" = 0 ]; then continue; fi
        if [ "$status" = exited ] || [ "$status" = dead ]; then
          fail_startup "${service} exited with code ${code}" "$service"
        fi
      elif before="$(awk -v s="$service" '$1 == s { print $5; exit }' <<<"$baseline")" &&
        [ $((restarts - ${before:-0})) -ge "$max_restarts" ]; then
        fail_startup "${service} restarted $((restarts - ${before:-0})) times while starting" "$service"
      elif [ "$status" = running ] && { [ "$want" = running ] || [ "$health" = healthy ]; }; then
        continue
      fi
      pending+=("$service")
    done
    [ "${#pending[@]}" -eq 0 ] && return 0
    if [ "$SECONDS" -ge "$deadline" ]; then
      fail_startup "Not ready after ${ready_timeout}s: ${pending[*]}" "${pending[@]}"
    fi
    sleep "$ready_interval"
  done
}

# Warn when the checkout changes an image input that the image tag, taken from
# the commit, does not include.
warn_uncommitted_inputs() {
  local changed
  # shellcheck disable=SC2046 # one argument per input path
  changed="$(git status --porcelain -- $(images_main inputs) 2>/dev/null || true)"
  if [ -n "$changed" ]; then
    log "Uncommitted changes to image build inputs are not in the prebuilt images:"
    printf '%s\n' "$changed" | sed 's/^/[qdash-demo]   /'
    log "To run them, build the images here: bash ${demo_dir}/demo.sh build-local"
  fi
}

# Pull the images of this commit that Docker does not have yet. Never builds.
ensure_images() {
  local refs ref missing=()
  refs="$(images_main refs)"
  for ref in $refs; do
    docker image inspect "$ref" >/dev/null 2>&1 || missing+=("$ref")
  done
  warn_uncommitted_inputs
  [ "${#missing[@]}" -eq 0 ] && return 0
  log "Pulling the prebuilt QDash Demo images"
  for ref in "${missing[@]}"; do
    if ! docker pull --quiet "$ref"; then
      log "Cannot pull ${ref}."
      log "The \"QDash Demo Images\" workflow (.github/workflows/demo-images.yml) publishes"
      log "the images when develop or main changes. Its run may still be in progress, no"
      log "published commit may have this checkout's build inputs yet, or the package may"
      log "not be public yet; see docs/developer-guide/demo-images.md."
      log "Then run: bash ${demo_dir}/demo.sh start"
      log "Or build the images in this codespace, which takes several minutes:"
      log "  bash ${demo_dir}/demo.sh build-local && bash ${demo_dir}/demo.sh start"
      exit 1
    fi
  done
}

build_image() {
  local dockerfile="$3" ref="${demo_registry}/$2:$6" arg build_args=()
  for arg in $4; do build_args+=(--build-arg "$arg"); done
  log "Building ${ref}"
  docker build -f "$dockerfile" "${build_args[@]}" -t "$ref" .
}

cmd_pull() {
  wait_for_docker
  prepare_env
  ensure_images
}

# Builds the images in this codespace under the tags start looks for, so
# start uses them instead of pulling.
cmd_build_local() {
  wait_for_docker
  prepare_env
  log "Building the QDash Demo images here (takes several minutes)"
  for_each_image build_image
}

cmd_start() {
  wait_for_docker
  prepare_env
  ensure_images
  log "Starting services"
  local deadline=$((SECONDS + ready_timeout))
  # up waits for the database healthchecks and setup jobs that compose.yaml
  # depends on. Bound this wait too: a migration can hang before up returns.
  # GNU timeout is included in the Ubuntu Codespaces base image.
  timeout --kill-after=5 "$ready_timeout" docker compose \
    -f compose.yaml -f "${demo_dir}/compose.yaml" \
    up -d --no-build "${services[@]}" || fail_startup \
    "Services did not start within ${ready_timeout}s or Compose failed" \
    mongo postgres calibration-migration agent-runtime-auth
  wait_ready "$deadline"
  log "Seeding the demo chip and its first run"
  # The API container already has the administrator credentials from .env and
  # reaches Caddy on the Compose network.
  compose exec -T api python - <"${demo_dir}/seed.py"
  cmd_credentials
}

# Stops the containers only; the database volumes and .env stay.
cmd_stop() {
  compose stop
}

cmd_status() {
  compose ps
}

env_value() {
  sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" .env | tail -n 1
}

cmd_credentials() {
  if [ ! -f .env ] || ! grep -qxF "$marker" .env; then
    log "No demo .env yet; read the creation log, then run: bash ${demo_dir}/demo.sh start"
    exit 1
  fi
  log "QDash:    $(client_url)/login (in Codespaces: Ports tab, port ${port})"
  log "User:     $(env_value QDASH_ADMIN_USERNAME)"
  log "Password: $(env_value QDASH_ADMIN_PASSWORD)"
}

case "${1:-start}" in
  pull) cmd_pull ;;
  build-local) cmd_build_local ;;
  start) cmd_start ;;
  stop) cmd_stop ;;
  status) cmd_status ;;
  credentials) cmd_credentials ;;
  *)
    echo "Usage: $0 pull|start|stop|status|credentials|build-local" >&2
    exit 2
    ;;
esac
